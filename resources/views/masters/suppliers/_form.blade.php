<script>
document.addEventListener('DOMContentLoaded', function () {

    /* ------------------------------------------------------------------ *
     * Conditional fields.
     *
     * The starting state is rendered by the server — see the top of this file.
     * What follows only reacts to the user changing the field each block
     * depends on, so nothing flashes into view and back out on load.
     *
     * Hidden, not disabled: a disabled input is still in the document but a
     * hidden one is what a user reads as "does not apply". Either way this is
     * a courtesy — SupplierRequest re-applies every one of these conditions
     * server-side, so a hand-posted GST number on an unregistered supplier is
     * dropped whatever the browser did.
     * ------------------------------------------------------------------ */

    /**
     * Which supplier types carry a GST number. Sent from the server rather
     * than hard-coded, because the sheet asks for the list to be extendable
     * and a type added next year has to answer this for itself.
     */
    const registeredTypes = @json($supplierTypeFlags);

    const supplierType = document.getElementById('supplier_type_id');
    const gstRow       = document.getElementById('gst-row');
    const gstInput     = document.getElementById('gst_number');
    const msmeToggle   = document.getElementById('is_msme');
    const msmeRow      = document.getElementById('msme-row');
    const partyType    = document.getElementById('party_type');
    const jobwork      = document.getElementById('jobwork-section');

    function show(element, visible) {
        element.classList.toggle('d-none', ! visible);
    }

    function applyGst() {
        const registered = registeredTypes[supplierType.value] === true;

        show(gstRow, registered);

        // Left visible when it holds a rejected value, so the error next to it
        // is not hidden along with the field it belongs to.
        if (! registered && ! gstInput.classList.contains('is-invalid')) {
            gstInput.value = '';
        }
    }

    function applyMsme() {
        show(msmeRow, msmeToggle.checked);
    }

    function applyJobwork() {
        show(jobwork, partyType.value === 'jobber' || partyType.value === 'both');
    }

    supplierType.addEventListener('change', applyGst);
    msmeToggle.addEventListener('change', applyMsme);
    partyType.addEventListener('change', applyJobwork);

    applyGst();
    applyMsme();
    applyJobwork();

    /* ------------------------------------------------------------------ *
     * Col L — other contact persons. Repeatable rows.
     * ------------------------------------------------------------------ */
    const rows     = document.getElementById('contact-rows');
    const template = document.getElementById('contact-row-template');
    const addBtn   = document.getElementById('add-contact');

    /**
     * Field names carry their row index, so a row added after one was removed
     * must not reuse an index still in the DOM — two inputs sharing
     * contacts[2][name] would silently drop one on submit.
     */
    function reindex() {
        rows.querySelectorAll('[data-contact-row]').forEach(function (row, index) {
            row.querySelectorAll('[name^="contacts"]').forEach(function (field) {
                field.name = field.name.replace(/contacts\[\d+\]/, 'contacts[' + index + ']');
            });
        });
    }

    rows.addEventListener('click', function (event) {
        const remove = event.target.closest('.js-remove-contact');
        if (! remove) return;

        const all = rows.querySelectorAll('[data-contact-row]');

        // Keep at least one row — an empty table has no affordance beyond the
        // button, and clearing the last row is the same outcome.
        if (all.length === 1) {
            all[0].querySelectorAll('input').forEach(function (field) { field.value = ''; });

            const select = all[0].querySelector('select');
            select?.tomselect ? select.tomselect.clear(true) : (select.value = '');
        } else {
            remove.closest('[data-contact-row]').remove();
        }

        reindex();
    });

    addBtn.addEventListener('click', function () {
        const index = rows.querySelectorAll('[data-contact-row]').length;
        const row   = template.content.cloneNode(true).querySelector('tr');

        row.querySelectorAll('[name*="__INDEX__"]').forEach(function (field) {
            field.name = field.name.replace('__INDEX__', index);
        });

        rows.appendChild(row);

        // The page-load sweep in app.js has already run, so a select added now
        // has to be upgraded here or it renders as a bare dropdown next to
        // three searchable ones.
        const select = row.querySelector('select[data-searchable]');
        if (select && typeof window.upgradeSearchableSelect === 'function') {
            window.upgradeSearchableSelect(select);
        }

        row.querySelector('input')?.focus();
    });

    /* ------------------------------------------------------------------ *
     * Secondary Contact Person toggle — hidden until asked for. Unchecking
     * resets the table to one blank row rather than leaving typed values
     * sitting in a hidden section that would still post on submit.
     * ------------------------------------------------------------------ */
    const secondaryToggle = document.getElementById('toggle-secondary-contacts');
    const secondaryWrap   = document.getElementById('secondary-contacts-wrap');

    secondaryToggle?.addEventListener('change', function () {
        secondaryWrap.classList.toggle('d-none', ! secondaryToggle.checked);

        if (secondaryToggle.checked) return;

        rows.querySelectorAll('[data-contact-row]').forEach(function (row, index) {
            if (index === 0) {
                row.querySelectorAll('input').forEach(function (field) { field.value = ''; });

                const select = row.querySelector('select');
                select?.tomselect ? select.tomselect.clear(true) : (select && (select.value = ''));
            } else {
                row.remove();
            }
        });
    });

    /* ------------------------------------------------------------------ *
     * "Tell me if a certain code is used already" (sheet col A).
     * A convenience only — the unique index is what actually enforces it.
     * ------------------------------------------------------------------ */
    const input    = document.getElementById('display_code');
    const feedback = document.querySelector('.js-code-feedback');
    const checkUrl = @json(route('masters.suppliers.check-code'));
    const ignoreId = @json($supplier?->id);
    const original = input.value.trim().toUpperCase();
    const resting  = feedback.textContent;
    let timer = null;

    function rest() {
        feedback.textContent = resting;
        feedback.className = 'form-text js-code-feedback';
    }

    input.addEventListener('input', function () {
        clearTimeout(timer);
        const value = input.value.trim().toUpperCase();

        // Unchanged on an edit form is not a clash with itself.
        if (value === '' || value === original) {
            input.classList.remove('is-invalid', 'is-valid');
            rest();
            return;
        }

        // Debounced so a 5-character code is one request, not five.
        timer = setTimeout(function () {
            const params = new URLSearchParams({ value: value });
            if (ignoreId) params.append('ignore', ignoreId);

            fetch(checkUrl + '?' + params, { headers: { 'Accept': 'application/json' } })
                .then(r => r.ok ? r.json() : Promise.reject())
                .then(function (data) {
                    input.classList.toggle('is-invalid', !data.available);
                    input.classList.toggle('is-valid', data.available);
                    feedback.textContent = data.available
                        ? 'Available.'
                        : 'Already used by another supplier — choose another.';
                    feedback.className = 'form-text js-code-feedback ' +
                        (data.available ? 'text-success' : 'text-danger');
                })
                // Network failure must not block the form. The unique index
                // still rejects a duplicate on submit.
                .catch(rest);
        }, 350);
    });

    /* ------------------------------------------------------------------ *
     * Agent commission — pick a rate from Agent Master (dropdown; no typing).
     * ------------------------------------------------------------------ */
    const agentSelect          = document.getElementById('agent_id');
    const commissionPick       = document.getElementById('agent_commission_pick');
    const agentCommissionValue = document.getElementById('agent_commission_value');
    const agentCommissionType  = document.getElementById('agent_commission_type');
    const agentCommissionHint  = document.getElementById('agent-commission-hint');
    const agentCommissions     = @json($agentCommissions ?? []);
    const savedCommissionValue = agentCommissionValue?.value || '';
    const savedCommissionType  = agentCommissionType?.value || '';

    function ratesFor(agentId) {
        if (! agentId) return [];
        const rows = agentCommissions[agentId] ?? agentCommissions[String(agentId)] ?? [];
        return Array.isArray(rows) ? rows : (rows ? [rows] : []);
    }

    function optionValue(row) {
        return row.type + '|' + String(row.value);
    }

    function fillHiddenFromPick() {
        if (! commissionPick || ! agentCommissionValue || ! agentCommissionType) return;
        const raw = commissionPick.value || '';
        if (! raw) {
            agentCommissionValue.value = '';
            agentCommissionType.value = '';
            return;
        }
        const parts = raw.split('|');
        agentCommissionType.value = parts[0] || '';
        agentCommissionValue.value = parts.slice(1).join('|') || '';
    }

    function rebuildCommissionPick(agentId, preferType, preferValue) {
        if (! commissionPick) return;

        const rates = ratesFor(agentId);
        commissionPick.innerHTML = '';

        if (! agentId) {
            commissionPick.appendChild(new Option('— Select agent first —', ''));
            commissionPick.disabled = true;
            fillHiddenFromPick();
            if (agentCommissionHint) {
                agentCommissionHint.textContent = 'Rates come from Agent Master. If an agent has more than one %, pick which one applies to this supplier.';
            }
            return;
        }

        if (rates.length === 0) {
            commissionPick.appendChild(new Option('— No rate on this agent —', ''));
            commissionPick.disabled = true;
            agentCommissionValue.value = '';
            agentCommissionType.value = '';
            if (agentCommissionHint) {
                agentCommissionHint.innerHTML = 'This agent has <strong>no % / pc rate</strong> in Agent Master (common for <strong>Supplier pays</strong>). Add a commission entry on the agent if needed.';
            }
            return;
        }

        commissionPick.disabled = false;
        if (rates.length > 1) {
            commissionPick.appendChild(new Option('— Select rate —', ''));
        }

        let matched = '';
        rates.forEach(function (row) {
            const value = optionValue(row);
            commissionPick.appendChild(new Option(row.label, value));
            if (preferType && preferValue !== '' && preferValue !== null
                && row.type === preferType
                && Number(row.value) === Number(preferValue)) {
                matched = value;
            }
        });

        if (matched) {
            commissionPick.value = matched;
        } else if (rates.length === 1) {
            commissionPick.value = optionValue(rates[0]);
        } else {
            commissionPick.value = '';
        }

        fillHiddenFromPick();

        if (agentCommissionHint) {
            agentCommissionHint.textContent = rates.length > 1
                ? 'This agent has more than one rate — pick which % or /pc applies to this supplier.'
                : 'Taken from Agent Master for this agent.';
        }
    }

    function onAgentChanged(agentId) {
        rebuildCommissionPick(agentId, null, null);
    }

    function bindAgentCommission() {
        if (! agentSelect) return;

        if (! agentSelect.dataset.commissionNativeBound) {
            agentSelect.dataset.commissionNativeBound = '1';
            agentSelect.addEventListener('change', function () {
                onAgentChanged(agentSelect.value);
            });
        }

        function attachTomSelect() {
            if (! agentSelect.tomselect || agentSelect.dataset.commissionTsBound) return;
            agentSelect.dataset.commissionTsBound = '1';
            agentSelect.tomselect.on('change', function (value) {
                onAgentChanged(value);
            });
        }

        attachTomSelect();
        setTimeout(attachTomSelect, 50);

        commissionPick?.addEventListener('change', fillHiddenFromPick);

        // Edit / validation old(): keep saved rate selected when possible.
        rebuildCommissionPick(agentSelect.value, savedCommissionType, savedCommissionValue);
    }

    bindAgentCommission();
});
</script>
