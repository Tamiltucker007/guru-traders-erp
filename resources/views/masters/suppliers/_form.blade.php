@props([
    'supplier' => null,
    'partyTypes' => [],
    'deliveryModes' => [],
    'supplierTypes' => [],
    'supplierTypeFlags' => [],
    'designations' => [],
    'categories' => [],
    // Filtered by party type; reloaded from the agents endpoint when it changes.
    'agents' => [],
    // Agent id => {type, value} from Agent Master — commission fields are read-only.
    'agentCommissions' => [],
    'countries' => [],
    // Change request #4 — "Default the Country to India".
    'indiaCountryId' => null,
    // Rendered server-side for the country/state already chosen; the cascade
    // reloads them from GeoController once a parent changes.
    'states' => [],
    'cities' => [],
])

@php
    /**
     * Supplier form — every field on the client's Supplier Master sheet, in the
     * sheet's own order, plus the party-type and jobwork fields from
     * DATABASE_SCHEMA.md §5. Column letters are noted against each field.
     *
     * Laid out one field per line, label on the left, grouped into sections —
     * same as Category, Product and Buyer. 27 columns in a flat grid is
     * unreadable.
     *
     * Three fields are conditional, and each is hidden rather than disabled so
     * the browser stops posting it at all; the request re-applies the same
     * condition server-side, so the JavaScript is a courtesy, not the rule:
     *
     *   col E  GST Number  — only when the chosen supplier type is registered
     *   col G  MSME reg no — only when "MSME registered" is ticked
     *   jobwork section    — only when the party type is Jobber or Both
     */

    // Categories already linked, for the multi-select (col R).
    $selectedCategories = $supplier?->categories->pluck('id')->all() ?? [];

    // Cols H–K live in supplier_contacts as the row flagged primary.
    $primary = $supplier?->contacts->firstWhere('is_primary', true);

    /**
     * Col L — "other contact persons". Everyone except the primary, or one
     * blank row to start from. Old input wins so a failed round-trip keeps
     * whatever the user had typed.
     */
    $extraContacts = old('contacts');

    if ($extraContacts === null) {
        $extraContacts = $supplier
            ? $supplier->contacts->where('is_primary', false)->map(fn ($c) => [
                'name'           => $c->name,
                'designation_id' => $c->designation_id,
                'mobile'         => $c->mobile,
                'email'          => $c->email,
            ])->values()->all()
            : [];
    }

    if ($extraContacts === []) {
        $extraContacts = [['name' => null, 'designation_id' => null, 'mobile' => null, 'email' => null]];
    }

    /**
     * Whether the Secondary Contact Person section starts open. Same
     * reasoning as the Buyer form's $secondaryContactsVisible.
     */
    $secondaryContactsVisible = old('contacts') !== null
        || ($supplier?->contacts->where('is_primary', false)->isNotEmpty() ?? false);

    /**
     * Initial visibility of the three conditional blocks, decided here rather
     * than left to the script below.
     *
     * If the server renders them all open and JavaScript closes them on load,
     * every edit of a trading supplier flashes a GST field that does not apply
     * before taking it away again. The script still owns what happens when the
     * user changes the field it depends on; this is only the starting state.
     *
     * A block holding a rejected value stays open either way — the error
     * message would otherwise be hidden along with the field it belongs to.
     */
    $selectedType = old('supplier_type_id', $supplier?->supplier_type_id);

    $gstVisible = ($supplierTypeFlags[$selectedType] ?? false) === true
        || $errors->has('gst_number');

    $msmeVisible = (bool) old('is_msme', $supplier?->is_msme)
        || $errors->has('msme_registration_no');

    $jobworkVisible = in_array(
        old('party_type', $supplier?->party_type ?? 'supplier'),
        ['jobber', 'both'],
        true
    );
@endphp

